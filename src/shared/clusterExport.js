/**
 * Offline cluster submission export for NodeChem Studio.
 *
 * Pure functions: no DOM, no filesystem, no Electron, and no network code.
 * The renderer plans the file set from the project graph; the main process
 * writes it to disk. One scheduler script is emitted per calculation node and
 * a submit-all wrapper expresses the graph's ordering edges as scheduler
 * dependencies (`afterok` on SLURM and PBS).
 *
 * Dependency rules mirror the local queue:
 *   - `dependency`, `checkpoint` and `branch` edges are ordering constraints.
 *   - `loop` edges are control flow, not ordering, and are ignored.
 *   - A downstream calculation depends on its nearest calculation ancestors;
 *     notes, merges and similar pass-through nodes do not become jobs.
 *   - A declared checkpoint hand-off is always a dependency, even when the
 *     inspector did not draw a checkpoint edge.
 */

import { outputNameFor } from './gaussianInput.js';
import { ORDERING_EDGE_TYPES, topologicalOrder } from './workflowGraph.js';

export const CLUSTER_FORMATS = Object.freeze(['slurm', 'pbs']);

// Durable export-format identifier. It is a format constant, not branding:
// `electron/runner/clusterFiles.js` rejects any other kind on import.
export const MANIFEST_KIND = 'nodechem-studio-cluster-export';
export const MANIFEST_VERSION = 1;

const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;
const SAFE_INPUT = /^[A-Za-z0-9._-]+\.(gjf|com)$/i;
const SAFE_OUTPUT = /^[A-Za-z0-9._-]+\.(out|log)$/i;
const SAFE_CHECKPOINT = /^[A-Za-z0-9._-]{1,124}\.chk$/i;
const MAX_INPUT_BYTES = 2 * 1024 * 1024;

function safeBase(value) {
  return String(value).replace(/[^A-Za-z0-9._-]/g, '_');
}

function oneLine(value, fallback = '') {
  return String(value ?? fallback).replace(/[\r\n\t]+/g, ' ').trim();
}

function byteLength(text) {
  return new TextEncoder().encode(text).length;
}

/** `%Mem` is stored in the .gjf; mirror that value in scheduler units. */
function resourcesFromInput(inputText) {
  const nprocMatch = inputText.match(/^%NProcShared\s*=\s*(\d+)\s*$/m);
  if (!nprocMatch) {
    throw new Error('Gaussian input is missing %NProcShared; cannot map the core count to the scheduler.');
  }
  const nproc = Number(nprocMatch[1]);
  if (!Number.isInteger(nproc) || nproc < 1) {
    throw new Error('%NProcShared must be a positive integer.');
  }

  const memMatch = inputText.match(/^%Mem\s*=\s*([0-9]+(?:\.[0-9]+)?)\s*(MB|GB|MW)\s*$/im);
  let memory = null;
  if (memMatch) {
    const value = Number(memMatch[1]);
    const unit = memMatch[2].toUpperCase();
    if (unit === 'MW') {
      // Gaussian megawords are 64-bit words: one MW is 8 MB.
      const mb = Math.round(value * 8);
      memory = { slurm: `${mb}M`, pbs: `${mb}mb` };
    } else if (unit === 'GB') {
      memory = { slurm: `${value}G`, pbs: `${value}gb` };
    } else {
      memory = { slurm: `${value}M`, pbs: `${value}mb` };
    }
  }
  return { nproc, memory };
}

function slurmScript(task, dependsOn, resources) {
  const base = safeBase(task.nodeId);
  const lines = [
    '#!/usr/bin/env bash',
    '# Generated by NodeChem Studio — offline cluster export.',
    `# Task: ${oneLine(task.title, task.nodeId)} (${task.nodeId})`,
    `# Requires: ${dependsOn.length ? dependsOn.join(', ') : 'none'}`,
    '# This script makes no network calls. It runs the licensed Gaussian',
    '# installation installed on the cluster.',
  ];
  if (dependsOn.length > 0) {
    lines.push(
      '# submit-all.sh wires this edge; to submit by hand, pass the upstream ids:',
      `#   sbatch --dependency=afterok:<jobid> ${base}.slurm`,
    );
  }
  lines.push(
    `#SBATCH --job-name=gn-${task.nodeId}`,
    `#SBATCH --cpus-per-task=${resources.nproc}`,
  );
  if (resources.memory) lines.push(`#SBATCH --mem=${resources.memory.slurm}`);
  lines.push(
    `#SBATCH --output=${base}.slurm.log`,
    `#SBATCH --error=${base}.slurm.err`,
    'set -euo pipefail',
    '',
    '# Gaussian scratch uses the node-local directory the scheduler provides.',
    'export GAUSS_SCRDIR="${TMPDIR:-/tmp}"',
    'mkdir -p "$GAUSS_SCRDIR"',
    '',
    '# g16 must be on PATH (for example after "module load gaussian"). Set',
    '# G16_EXE to an absolute path when it is not.',
    `"\${G16_EXE:-g16}" "${task.inputName}"`,
    '',
  );
  return lines.join('\n');
}

function pbsScript(task, dependsOn, resources) {
  const base = safeBase(task.nodeId);
  const lines = [
    '#!/usr/bin/env bash',
    '# Generated by NodeChem Studio — offline cluster export.',
    `# Task: ${oneLine(task.title, task.nodeId)} (${task.nodeId})`,
    `# Requires: ${dependsOn.length ? dependsOn.join(', ') : 'none'}`,
    '# This script makes no network calls. It runs the licensed Gaussian',
    '# installation installed on the cluster.',
  ];
  if (dependsOn.length > 0) {
    lines.push(
      '# submit-all.sh wires this edge; to submit by hand, pass the upstream ids:',
      `#   qsub -W depend=afterok:<jobid> ${base}.pbs`,
    );
  }
  lines.push(
    `#PBS -N gn-${task.nodeId}`,
    `#PBS -l nodes=1:ppn=${resources.nproc}`,
  );
  if (resources.memory) lines.push(`#PBS -l mem=${resources.memory.pbs}`);
  lines.push(
    '#PBS -j oe',
    `#PBS -o ${base}.pbs.log`,
    'set -euo pipefail',
    '',
    '# PBS starts jobs in the home directory; run beside the staged inputs.',
    'cd "${PBS_O_WORKDIR:?PBS_O_WORKDIR is not set}"',
    '',
    '# Gaussian scratch uses the node-local directory the scheduler provides.',
    'export GAUSS_SCRDIR="${TMPDIR:-/tmp}"',
    'mkdir -p "$GAUSS_SCRDIR"',
    '',
    '# g16 must be on PATH (for example after "module load gaussian"). Set',
    '# G16_EXE to an absolute path when it is not.',
    `"\${G16_EXE:-g16}" "${task.inputName}"`,
    '',
  );
  return lines.join('\n');
}

function submitAllScript(format, jobs) {
  const lines = [
    '#!/usr/bin/env bash',
    '# Generated by NodeChem Studio — offline cluster export.',
    '# Submit every calculation in dependency order. A downstream job starts',
    '# only after all of its upstream jobs finished successfully (afterok).',
    'set -euo pipefail',
    'cd "$(dirname "$0")"',
    'declare -A GN_JOB',
    '',
  ];
  for (const job of jobs) {
    const ref = `GN_JOB['${job.nodeId}']`;
    if (format === 'slurm') {
      const deps = job.dependsOn.map((id) => `\${GN_JOB['${id}']%%;*}`).join(':');
      const depArgument = job.dependsOn.length ? `--dependency=afterok:${deps} ` : '';
      lines.push(`${ref}=$(sbatch --parsable ${depArgument}'${job.scriptName}')`);
    } else {
      const deps = job.dependsOn.map((id) => `\${GN_JOB['${id}']}`).join(':');
      const depArgument = job.dependsOn.length ? `-W depend=afterok:${deps} ` : '';
      lines.push(`${ref}=$(qsub ${depArgument}'${job.scriptName}')`);
    }
  }
  lines.push('', `echo "Submitted ${jobs.length} Gaussian job(s)."`, '');
  return lines.join('\n');
}

function readmeText(format, jobs) {
  const upper = format === 'slurm' ? 'SLURM' : 'PBS';
  const schedulerFlag = format === 'slurm' ? '--dependency=afterok:...' : '-W depend=afterok:...';
  return [
    `NodeChem Studio — ${upper} cluster export`,
    '',
    'Files',
    '  manifest.json      machine-readable plan: dependencies, inputs, outputs, gates',
    '  submit-all.sh      submits every job in dependency order',
    '  <task>.gjf         the exact Gaussian input the local runner would write',
    `  <task>.${format}       one scheduler script per calculation node`,
    '',
    'Usage',
    '  1. Copy this folder to a filesystem visible to the cluster compute nodes.',
    '  2. Review manifest.json; every node lists dependsOn and its gate set.',
    '  3. Submit from inside this folder:  bash submit-all.sh',
    '  4. When the jobs finish, copy the folder back and choose',
    '     "Import cluster results" in the app\'s overflow menu.',
    '',
    'Dependencies',
    `  submit-all.sh passes ${schedulerFlag} for every dependency edge and`,
    '  every checkpoint hand-off in the project graph. A downstream job never',
    '  starts unless all upstream jobs exited successfully.',
    '',
    'Resources and scratch',
    '  %NProcShared  ->  --cpus-per-task (SLURM) / ppn (PBS)',
    '  %Mem         ->  --mem (SLURM) / -l mem (PBS)',
    '  GAUSS_SCRDIR is set to $TMPDIR, the per-job node-local scratch directory.',
    '  The scripts assume g16 is on PATH; set G16_EXE to an absolute path otherwise.',
    '',
    'Checkpoint hand-offs',
    '  %OldChk refers to the upstream .chk file. Every job runs in this folder,',
    '  so the export must live on a filesystem shared by the compute nodes.',
    '',
    'Licence',
    '  Gaussian is licensed commercial software. Running these scripts requires',
    '  a Gaussian licence that covers the cluster, its users, and every node',
    '  that executes them. NodeChem Studio does not include, copy, or',
    '  redistribute Gaussian; you must install and licence it yourself. Check',
    '  your licence terms before submitting — site licences may restrict named',
    '  users or hosts.',
    '',
    'Network',
    '  This export contains no network code. Nothing is submitted until you run',
    '  submit-all.sh yourself.',
    '',
    `Jobs: ${jobs.length}`,
    '',
  ].join('\n');
}

function gateOptionsFor(raw) {
  const gates = raw && typeof raw === 'object' ? raw : {};
  return {
    expectedImaginary: Number.isInteger(gates.expectedImaginary) ? gates.expectedImaginary : null,
    minMagnitude: gates.minMagnitude === undefined || gates.minMagnitude === null
      ? 50 : Number(gates.minMagnitude),
    requireOptimization: Boolean(gates.requireOptimization),
    requireFrequency: Boolean(gates.requireFrequency),
    requireThermochemistry: Boolean(gates.requireThermochemistry),
    requireFinalEnergy: Boolean(gates.requireFinalEnergy),
  };
}

function manifestEdge(edge) {
  const record = { from: String(edge.from), to: String(edge.to), type: String(edge.type) };
  if (edge.branch) record.branch = String(edge.branch);
  return record;
}

/**
 * Build the complete file set for one scheduler format.
 *
 * `tasks` is the workflow task list the renderer already builds for the local
 * queue (calc tasks carry `inputText`); non-calculation tasks are used only to
 * resolve graph hops. `edges` are the project edges.
 */
export function planClusterExport({
  format,
  projectName = 'Untitled project',
  tasks = [],
  edges = [],
  createdAt = new Date().toISOString(),
} = {}) {
  if (!CLUSTER_FORMATS.includes(format)) {
    throw new Error('Cluster format must be either "slurm" or "pbs".');
  }
  if (!Array.isArray(tasks) || tasks.length === 0) {
    throw new Error('The project has no nodes to export.');
  }
  if (!Array.isArray(edges)) throw new Error('Project edges must be an array.');

  const allIds = new Set();
  for (const task of tasks) {
    const nodeId = String(task?.nodeId || '');
    if (!SAFE_ID.test(nodeId)) throw new Error(`Node id "${nodeId}" is not safe for a cluster export.`);
    if (allIds.has(nodeId)) throw new Error(`Duplicate node id "${nodeId}".`);
    allIds.add(nodeId);
  }

  const orderingEdges = edges.filter((edge) => ORDERING_EDGE_TYPES.includes(edge?.type));
  for (const edge of orderingEdges) {
    if (!allIds.has(String(edge.from)) || !allIds.has(String(edge.to))) {
      throw new Error(`Edge ${edge.from} -> ${edge.to} references a node that is not in the project.`);
    }
  }

  const ordered = topologicalOrder(tasks.map((task) => ({ nodeId: task.nodeId })), edges);
  if (ordered.cycle) {
    throw new Error(`The graph contains a cycle: ${ordered.cycle.join(' -> ')}.`);
  }
  const orderIndex = new Map(ordered.order.map((nodeId, index) => [nodeId, index]));

  const byId = new Map(tasks.map((task) => [String(task.nodeId), task]));
  const conformerBlocks = tasks.filter((task) => task?.type === 'generate');
  if (conformerBlocks.length > 0) {
    // A cluster job that read the project geometry instead of the chosen member
    // would be a silent chemistry change, so this refuses rather than exports
    // a plan whose first calculation is built from the wrong structure.
    const names = conformerBlocks.map((task) => `"${task.title || task.nodeId}"`).join(', ');
    throw new Error(`Cluster export does not include Generate blocks: ${names}. Run the ensemble, choose the member, and export the calculation blocks from a project whose geometry is that member.`);
  }
  const calcTasks = tasks.filter((task) => task?.type === 'calculate');
  if (calcTasks.length === 0) {
    throw new Error('The project has no calculation blocks to export.');
  }
  const calcIds = new Set(calcTasks.map((task) => String(task.nodeId)));

  const warnings = [];
  const incoming = new Map(tasks.map((task) => [String(task.nodeId), []]));
  for (const edge of orderingEdges) {
    incoming.get(String(edge.to)).push(String(edge.from));
  }

  /** Nearest calculation ancestors, walking through notes/conditions/merges. */
  function calculationAncestors(nodeId) {
    const found = new Set();
    const seen = new Set([nodeId]);
    const queue = [...(incoming.get(nodeId) || [])];
    while (queue.length > 0) {
      const id = queue.shift();
      if (seen.has(id)) continue;
      seen.add(id);
      if (calcIds.has(id)) {
        found.add(id);
        continue;
      }
      queue.push(...(incoming.get(id) || []));
    }
    return [...found].sort((a, b) => orderIndex.get(a) - orderIndex.get(b));
  }

  const checkpointOwner = new Map();
  const jobs = [];
  for (const task of calcTasks) {
    const nodeId = String(task.nodeId);
    const inputName = String(task.inputName || `${safeBase(nodeId)}.gjf`);
    if (!SAFE_INPUT.test(inputName)) {
      throw new Error(`Task "${nodeId}" has an unsafe Gaussian input name.`);
    }
    const inputText = String(task.inputText || '');
    if (!inputText.trim()) throw new Error(`Task "${nodeId}" has no Gaussian input text.`);
    if (byteLength(inputText) > MAX_INPUT_BYTES) {
      throw new Error(`Task "${nodeId}" input is larger than 2 MiB.`);
    }
    const outputName = String(task.outputName || outputNameFor(inputName));
    if (!SAFE_OUTPUT.test(outputName)) {
      throw new Error(`Task "${nodeId}" has an unsafe Gaussian output name.`);
    }
    const checkpointName = String(task.checkpointName || `${safeBase(nodeId)}.chk`);
    if (!SAFE_CHECKPOINT.test(checkpointName)) {
      throw new Error(`Task "${nodeId}" has an unsafe checkpoint name.`);
    }
    if (checkpointOwner.has(checkpointName)) {
      throw new Error(
        `Checkpoint "${checkpointName}" is written by both "${checkpointOwner.get(checkpointName)}" and "${nodeId}"; a shared export folder cannot hold both.`,
      );
    }
    checkpointOwner.set(checkpointName, nodeId);

    const resources = resourcesFromInput(inputText);
    jobs.push({
      nodeId,
      title: oneLine(task.title, nodeId),
      kind: oneLine(task.kind, 32),
      inputName,
      outputName,
      checkpointName,
      inputText,
      gates: gateOptionsFor(task.gates),
      resources,
      checkpointFrom: task.checkpointFrom || null,
      dependsOn: calculationAncestors(nodeId),
    });
  }

  const jobById = new Map(jobs.map((job) => [job.nodeId, job]));
  for (const job of jobs) {
    if (!job.checkpointFrom) continue;
    const sourceId = String(job.checkpointFrom.nodeId || '');
    if (sourceId === job.nodeId) {
      throw new Error(`Task "${job.nodeId}" cannot hand off a checkpoint from itself.`);
    }
    const source = byId.get(sourceId);
    if (!source || source.type !== 'calculate' || !jobById.has(String(source.nodeId))) {
      throw new Error(`Task "${job.nodeId}" hands off from a node that is not an exported calculation.`);
    }
    const sourceJob = jobById.get(String(source.nodeId));
    const declared = String(job.checkpointFrom.checkpoint || '');
    if (declared && declared !== sourceJob.checkpointName) {
      throw new Error(
        `Checkpoint mismatch: "${job.title}" reads ${declared} but "${sourceJob.title}" writes ${sourceJob.checkpointName}.`,
      );
    }
    if (!job.dependsOn.includes(sourceJob.nodeId)) {
      job.dependsOn = [...job.dependsOn, sourceJob.nodeId]
        .sort((a, b) => orderIndex.get(a) - orderIndex.get(b));
    }
  }

  for (const edge of orderingEdges) {
    if (edge.type !== 'checkpoint') continue;
    const target = jobById.get(String(edge.to));
    const source = jobById.get(String(edge.from));
    if (target && source && target.checkpointFrom?.nodeId !== source.nodeId) {
      warnings.push(
        `Checkpoint edge ${source.nodeId} -> ${target.nodeId} has no %OldChk hand-off in ${target.inputName}; the dependency is ordering-only.`,
      );
    }
  }

  for (const task of tasks) {
    const nodeId = String(task.nodeId);
    if (task.type === 'condition') {
      warnings.push(
        `Condition node "${oneLine(task.title, nodeId)}" (${nodeId}) is not schedulable. Downstream calculations are exported with unconditional afterok dependencies on its upstream work; verify the branch decision manually.`,
      );
    } else if (task.type === 'loop') {
      warnings.push(
        `Loop node "${oneLine(task.title, nodeId)}" (${nodeId}) is not exported. Retries must be handled outside this script set.`,
      );
    } else if (task.type === 'merge') {
      warnings.push(
        `Merge node "${oneLine(task.title, nodeId)}" (${nodeId}) is not scheduled; its calculation inputs become direct dependencies of downstream jobs.`,
      );
    }
  }

  jobs.sort((a, b) => orderIndex.get(a.nodeId) - orderIndex.get(b.nodeId));
  for (const job of jobs) {
    job.scriptName = `${safeBase(job.nodeId)}.${format}`;
  }

  const files = [];
  files.push({ name: 'README.txt', kind: 'readme', content: readmeText(format, jobs) });

  const manifest = {
    schemaVersion: MANIFEST_VERSION,
    kind: MANIFEST_KIND,
    format,
    project: oneLine(projectName, 'Untitled project'),
    createdAt,
    generator: 'NodeChem Studio cluster export',
    network: 'none',
    warnings,
    nodes: jobs.map((job) => ({
      nodeId: job.nodeId,
      type: 'calculate',
      title: job.title,
      kind: job.kind || 'Calculate',
      inputName: job.inputName,
      outputName: job.outputName,
      checkpointName: job.checkpointName,
      scriptName: job.scriptName,
      dependsOn: job.dependsOn,
      gates: job.gates,
    })),
    edges: orderingEdges.map(manifestEdge),
  };
  files.push({ name: 'manifest.json', kind: 'manifest', content: `${JSON.stringify(manifest, null, 2)}\n` });
  files.push({ name: 'submit-all.sh', kind: 'submit', content: submitAllScript(format, jobs) });

  for (const job of jobs) {
    files.push({ name: job.inputName, kind: 'input', content: job.inputText });
    files.push({
      name: job.scriptName,
      kind: 'script',
      content: format === 'slurm'
        ? slurmScript(job, job.dependsOn, job.resources)
        : pbsScript(job, job.dependsOn, job.resources),
    });
  }

  return { format, files, manifest, warnings, jobs };
}
